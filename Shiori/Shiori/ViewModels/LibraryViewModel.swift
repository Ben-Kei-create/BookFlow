import SwiftUI

/// ライブラリ画面の状態管理ViewModel
@MainActor
final class LibraryViewModel: ObservableObject {

    // MARK: - 公開プロパティ

    /// ダウンロード済み書籍一覧
    @Published var books: [Book] = []

    /// 読み込み中フラグ
    @Published var isLoading = false

    /// エラーメッセージ
    @Published var errorMessage: String?

    // MARK: - 内部依存

    /// 青空文庫パーサー
    private let parser = AozoraBunkoParser()

    // MARK: - 初期化

    init() {
        loadSampleBooks()
    }

    // MARK: - サンプルデータ

    /// MVPデモ用のサンプル書籍を読み込む
    private func loadSampleBooks() {
        // 宮沢賢治「銀河鉄道の夜」のサンプル抜粋
        let gingatetsudo = parser.parseFromString(
            text: SampleTexts.gingatetsudoNoYoru,
            title: "銀河鉄道の夜",
            author: "宮沢賢治"
        )

        // 太宰治「走れメロス」のサンプル抜粋
        let hashireMerosu = parser.parseFromString(
            text: SampleTexts.hashireMerosu,
            title: "走れメロス",
            author: "太宰治"
        )

        // 夏目漱石「こころ」のサンプル抜粋
        let kokoro = parser.parseFromString(
            text: SampleTexts.kokoro,
            title: "こころ",
            author: "夏目漱石"
        )

        // 芥川龍之介「羅生門」のサンプル抜粋
        let rashomon = parser.parseFromString(
            text: SampleTexts.rashomon,
            title: "羅生門",
            author: "芥川龍之介"
        )

        books = [gingatetsudo, hashireMerosu, kokoro, rashomon]
    }

